CREATE TABLE service_requests (
                                  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  requester_id    BIGINT        NOT NULL,
                                  provider_id     BIGINT        NOT NULL,
                                  category_id     BIGINT        NOT NULL,
                                  description     VARCHAR(2000) NOT NULL,
                                  city            VARCHAR(100)  NOT NULL,
                                  desired_date    DATE,
                                  additional_info VARCHAR(1000),
                                  status          VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE',
                                  version         BIGINT        NOT NULL DEFAULT 0,
                                  created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                  updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                  CONSTRAINT fk_service_requests_requester FOREIGN KEY (requester_id) REFERENCES users (id),
                                  CONSTRAINT fk_service_requests_provider  FOREIGN KEY (provider_id)  REFERENCES provider_profiles (id),
                                  CONSTRAINT fk_service_requests_category  FOREIGN KEY (category_id)  REFERENCES categories (id),
                                  CONSTRAINT ck_service_requests_status CHECK (
                                      status IN ('PENDENTE', 'EM_NEGOCIACAO', 'ACEITA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')
                                      )
);

CREATE INDEX idx_service_requests_requester
    ON service_requests (requester_id, created_at DESC);

CREATE INDEX idx_service_requests_provider_status
    ON service_requests (provider_id, status, created_at DESC);

CREATE UNIQUE INDEX uq_service_requests_open
    ON service_requests (requester_id, provider_id, category_id)
    WHERE status IN ('PENDENTE', 'EM_NEGOCIACAO', 'ACEITA', 'EM_ANDAMENTO');