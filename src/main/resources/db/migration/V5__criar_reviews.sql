ALTER TABLE provider_profiles
    ADD COLUMN rating_avg   NUMERIC(3,2) NOT NULL DEFAULT 0,
    ADD COLUMN rating_count INTEGER      NOT NULL DEFAULT 0;

CREATE TABLE reviews (
                         id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         service_request_id BIGINT       NOT NULL,
                         provider_id        BIGINT       NOT NULL,
                         reviewer_id        BIGINT       NOT NULL,
                         rating             INTEGER      NOT NULL,
                         comment            VARCHAR(1000),
                         status             VARCHAR(20)  NOT NULL DEFAULT 'VISIBLE',
                         created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
                         updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
                         CONSTRAINT uq_reviews_service_request UNIQUE (service_request_id),
                         CONSTRAINT fk_reviews_service_request FOREIGN KEY (service_request_id) REFERENCES service_requests (id),
                         CONSTRAINT fk_reviews_provider        FOREIGN KEY (provider_id)        REFERENCES provider_profiles (id),
                         CONSTRAINT fk_reviews_reviewer        FOREIGN KEY (reviewer_id)        REFERENCES users (id),
                         CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
                         CONSTRAINT ck_reviews_status CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX idx_reviews_provider_status ON reviews (provider_id, status, created_at DESC);
