CREATE TABLE provider_profiles (
                                   id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   user_id           BIGINT        NOT NULL,
                                   professional_name VARCHAR(120)  NOT NULL,
                                   description       VARCHAR(1000),
                                   whatsapp          VARCHAR(13)   NOT NULL,
                                   city              VARCHAR(100)  NOT NULL,
                                   photo_url         VARCHAR(500),
                                   available         BOOLEAN       NOT NULL DEFAULT TRUE,
                                   created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                   updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                   CONSTRAINT uq_provider_profiles_user UNIQUE (user_id),
                                   CONSTRAINT fk_provider_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
                                   CONSTRAINT ck_provider_profiles_whatsapp CHECK (whatsapp ~ '^55[1-9][1-9]9[0-9]{8}$')
    );

CREATE TABLE provider_service_areas (
                                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        provider_id BIGINT       NOT NULL,
                                        city        VARCHAR(100) NOT NULL,
                                        city_key    VARCHAR(100) NOT NULL,
                                        CONSTRAINT fk_service_areas_provider FOREIGN KEY (provider_id)
                                            REFERENCES provider_profiles (id) ON DELETE CASCADE,
                                        CONSTRAINT uq_service_areas_provider_city UNIQUE (provider_id, city_key)
);

CREATE INDEX idx_service_areas_city_key ON provider_service_areas (city_key);

CREATE TABLE provider_offerings (
                                    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    provider_id BIGINT       NOT NULL,
                                    category_id BIGINT       NOT NULL,
                                    price_info  VARCHAR(100),
                                    CONSTRAINT fk_offerings_provider FOREIGN KEY (provider_id)
                                        REFERENCES provider_profiles (id) ON DELETE CASCADE,
                                    CONSTRAINT fk_offerings_category FOREIGN KEY (category_id)
                                        REFERENCES categories (id),
                                    CONSTRAINT uq_offerings_provider_category UNIQUE (provider_id, category_id)
);

CREATE INDEX idx_offerings_category ON provider_offerings (category_id);